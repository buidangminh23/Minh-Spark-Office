export function drillsForTrack(track: MosTrackId, level?: MosLevel, version?: MosVersion): MosDrillQuestion[] {
  const list = MOS_DRILLS.filter((q) => {
    if (q.track !== track) return false;
    if (!version) return !q.version;
    return !q.version || q.version === version;
  });
  if (level === 'associate') return list.filter((q) => q.level === 'associate');
  return list;
}
