export const matchCase = (source: string, replacement: string) => {
  if (source && source === source.toLocaleUpperCase('vi') && source.length > 1) return replacement.toLocaleUpperCase('vi');
  if (source && source[0] === source[0].toLocaleUpperCase('vi') && source[0] !== source[0].toLocaleLowerCase('vi')) return replacement[0].toLocaleUpperCase('vi') + replacement.slice(1);
  return replacement;
};
